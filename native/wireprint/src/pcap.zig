const testing = std.testing;
const fixtures = @import("fixtures");
const hex = @import("hex.zig");

fn expectErrorName(name: []const u8, result: anytype) !void {
    if (result) |_| {
        std.debug.print("expected error.{s}, got a value\n", .{name});
        return error.TestExpectedError;
    } else |err| try testing.expectEqualStrings(name, @errorName(err));
}

test "spec/test-vectors.json: magic selects byte order and precision; header sizes and link types" {
    const gpa = testing.allocator;
    const parsed = try std.json.parseFromSlice(std.json.Value, gpa, @import("spec").test_vectors_json, .{});
    defer parsed.deinit();
    const spec = (parsed.value.object.get("pcap") orelse return error.TestUnexpectedResult).object;

    try testing.expectEqual(spec.get("global_header_len").?.integer, global_header_len);
    try testing.expectEqual(spec.get("record_header_len").?.integer, record_header_len);
    const lt = spec.get("linktype").?.object;
    try testing.expectEqual(lt.get("NULL_BSD_LOOPBACK").?.integer, @intFromEnum(LinkType.null));
    try testing.expectEqual(lt.get("ETHERNET").?.integer, @intFromEnum(LinkType.ethernet));
    try testing.expectEqual(lt.get("RAW_IP").?.integer, @intFromEnum(LinkType.raw));
    try testing.expectEqual(lt.get("LINUX_SLL").?.integer, @intFromEnum(LinkType.linux_sll));

    const cases = [_]struct { key: []const u8, endian: std.builtin.Endian, nano: bool }{
        .{ .key = "magic_le_usec", .endian = .little, .nano = false },
        .{ .key = "magic_be_usec", .endian = .big, .nano = false },
        .{ .key = "magic_le_nsec", .endian = .little, .nano = true },
        .{ .key = "magic_be_nsec", .endian = .big, .nano = true },
    };
    for (cases) |c| {
        errdefer std.debug.print("case {s}\n", .{c.key});
        var buf: [global_header_len + record_header_len + 3]u8 = undefined;
        _ = try hex.decode(buf[0..4], spec.get(c.key).?.string);
        std.mem.writeInt(u16, buf[4..6], 2, c.endian);
        std.mem.writeInt(u16, buf[6..8], 4, c.endian);
        std.mem.writeInt(u32, buf[8..12], 0, c.endian);
        std.mem.writeInt(u32, buf[12..16], 0, c.endian);
        std.mem.writeInt(u32, buf[16..20], 65535, c.endian);
        // FCS metadata in the upper bits must not leak into the link type.
        std.mem.writeInt(u32, buf[20..24], 0x1000_0001, c.endian);
        std.mem.writeInt(u32, buf[24..28], 1_790_164_800, c.endian);
        std.mem.writeInt(u32, buf[28..32], 999_999_999, c.endian);
        std.mem.writeInt(u32, buf[32..36], 3, c.endian);
        std.mem.writeInt(u32, buf[36..40], 60, c.endian);
        @memcpy(buf[40..43], "abc");

        var r = try Reader.init(&buf);
        try testing.expectEqual(c.endian, r.header.endian);
        try testing.expectEqual(c.nano, r.header.nanosecond);
        try testing.expectEqual(@as(u16, 2), r.header.version_major);
        try testing.expectEqual(@as(u16, 4), r.header.version_minor);
        try testing.expectEqual(@as(u32, 65535), r.header.snaplen);
        try testing.expectEqual(LinkType.ethernet, r.header.link_type);
        const rec = (try r.next()) orelse return error.TestUnexpectedResult;
        try testing.expectEqual(@as(u32, 1_790_164_800), rec.ts_sec);
        try testing.expectEqual(@as(u32, 999_999_999), rec.ts_frac);
        try testing.expectEqual(@as(u32, 60), rec.orig_len);
        try testing.expectEqualStrings("abc", rec.data);
        try testing.expectEqual(@as(?Record, null), try r.next());
    }
}

test "fixtures: global header, record count, lengths, timestamps, zero-copy data" {
    const gpa = testing.allocator;
    for (fixtures.pcap.all) |fx| {
        errdefer std.debug.print("fixture {s}\n", .{fx.name});
        const parsed = try fixtures.pcap.parseExpected(gpa, fx.expected_json);
        defer parsed.deinit();
        const exp = parsed.value;
        try testing.expectEqualStrings(fx.name, exp.name);
        try testing.expectEqual(exp.file_len, fx.bytes.len);
        var magic_hex: [8]u8 = undefined;
        try testing.expectEqualStrings(exp.magic_bytes, hex.encode(&magic_hex, fx.bytes[0..4]));

        var r = try Reader.init(fx.bytes);
        try testing.expectEqual(exp.endian, r.header.endian);
        try testing.expectEqual(exp.nanosecond, r.header.nanosecond);
        try testing.expectEqual(exp.version_major, r.header.version_major);
        try testing.expectEqual(exp.version_minor, r.header.version_minor);
        try testing.expectEqual(exp.snaplen, r.header.snaplen);
        try testing.expectEqual(exp.linktype, @intFromEnum(r.header.link_type));

        try testing.expectEqual(exp.record_count, exp.records.len);
        for (exp.records) |er| {
            const rec = (try r.next()) orelse return error.TestUnexpectedResult;
            try testing.expectEqual(er.ts_sec, rec.ts_sec);
            try testing.expectEqual(er.ts_frac, rec.ts_frac);
            try testing.expectEqual(er.incl_len, rec.data.len);
            try testing.expectEqual(er.orig_len, rec.orig_len);
            // Zero-copy: the record data is the slice right after its 16-byte header in the input.
            try testing.expectEqual(er.offset + record_header_len, @intFromPtr(rec.data.ptr) - @intFromPtr(fx.bytes.ptr));
            if (exp.nanosecond) try testing.expect(rec.ts_frac >= 1_000_000 or rec.ts_frac % 1000 != 0);
        }
        if (exp.trailing_error) |name| {
            try expectErrorName(name, r.next());
            // The failed read does not advance; the error is sticky.
            try expectErrorName(name, r.next());
        } else {
            try testing.expectEqual(@as(?Record, null), try r.next());
        }
    }
}

test "error paths: pcapng, unknown magic, short headers, truncated record header, incl_len > orig_len" {
    // pcapng Section Header Block: block type 0a0d0d0a, block length 28, byte-order magic 1a2b3c4d.
    const pcapng_shb = [_]u8{ 0x0a, 0x0d, 0x0d, 0x0a, 0x1c, 0, 0, 0, 0x4d, 0x3c, 0x2b, 0x1a } ++ [_]u8{0} ** 20;
    try testing.expectError(error.UnsupportedFormat, Reader.init(&pcapng_shb));
    const unknown = [_]u8{ 0xde, 0xad, 0xbe, 0xef } ++ [_]u8{0} ** 20;
    try testing.expectError(error.UnsupportedFormat, Reader.init(&unknown));
    try testing.expectError(error.Truncated, Reader.init(&.{}));
    try testing.expectError(error.Truncated, Reader.init(&.{ 0xd4, 0xc3, 0xb2 }));

    const fx = fixtures.pcap.chrome_153_macos_lo0_1seg;
    const parsed = try fixtures.pcap.parseExpected(testing.allocator, fx.expected_json);
    defer parsed.deinit();
    const recs = parsed.value.records;

    // Valid magic but global header cut short.
    try testing.expectError(error.Truncated, Reader.init(fx.bytes[0 .. global_header_len - 1]));
    // Major version 1 is not the legacy format this reader knows.
    var v1 = fx.bytes[0..global_header_len].*;
    std.mem.writeInt(u16, v1[4..6], 1, .little);
    try testing.expectError(error.UnsupportedFormat, Reader.init(&v1));

    // Exactly at a record boundary: clean end of file.
    {
        var r = try Reader.init(fx.bytes[0..recs[1].offset]);
        _ = (try r.next()) orelse return error.TestUnexpectedResult;
        try testing.expectEqual(@as(?Record, null), try r.next());
    }
    // Cut inside the second record header: first record ok, then Truncated.
    {
        var r = try Reader.init(fx.bytes[0 .. recs[1].offset + 10]);
        _ = (try r.next()) orelse return error.TestUnexpectedResult;
        try testing.expectError(error.Truncated, r.next());
    }
    // Every cut point inside the file yields Truncated for the partial record, never a panic.
    for (global_header_len..fx.bytes.len) |cut| {
        var r = try Reader.init(fx.bytes[0..cut]);
        var complete: usize = 0;
        while (r.next()) |maybe| {
            if (maybe == null) break;
            complete += 1;
        } else |err| try testing.expectEqual(error.Truncated, err);
        try testing.expect(complete <= recs.len);
    }
    // incl_len > orig_len contradicts itself.
    {
        const copy = try testing.allocator.dupe(u8, fx.bytes);
        defer testing.allocator.free(copy);
        const off = recs[0].offset;
        std.mem.writeInt(u32, copy[off + 12 ..][0..4], recs[0].incl_len - 1, .little);
        var r = try Reader.init(copy);
        try testing.expectError(error.Malformed, r.next());
    }
}
