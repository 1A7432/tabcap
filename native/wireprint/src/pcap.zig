//! Legacy pcap file reader.
//! Spec: https://www.tcpdump.org/manpages/pcap-savefile.5.txt and draft-ietf-opsawg-pcap
//! (https://datatracker.ietf.org/doc/draft-ietf-opsawg-pcap/), also https://wiki.wireshark.org/Development/LibpcapFileFormat.
//! Global header 24 bytes, per-record header 16 bytes (ts_sec, ts_frac, incl_len, orig_len). The magic,
//! read as written by the capturing host, selects byte order and timestamp precision:
//!   a1b2c3d4 / d4c3b2a1 -> microseconds, a1b23c4d / 4d3cb2a1 -> nanoseconds (spec/test-vectors.json `pcap`).
//! pcapng (0a0d0d0a) is NOT supported (convert with `tshark -F pcap`). Zero-copy: records borrow from the input.
//! Oracle: fixtures/pcap/*.pcap and *.expected.json generated by tools/mkpcap.py (values the generator wrote,
//! re-read by an independent struct-based reader in the same script); magic/length constants from
//! spec/test-vectors.json. Reproduce: `python3 tools/mkpcap.py && zig build test`; `tcpdump -r <file> -nn`
//! gives a third opinion on record count and timestamps.
const std = @import("std");

pub const ParseError = error{ Truncated, Malformed, UnsupportedFormat };

pub const global_header_len = 24;
pub const record_header_len = 16;

/// Magic values as the writer's host would read them; stored in the writer's byte order.
pub const magic_usec: u32 = 0xa1b2c3d4;
pub const magic_nsec: u32 = 0xa1b23c4d;
/// pcapng Section Header Block type (byte-order independent).
pub const pcapng_magic: u32 = 0x0a0d0d0a;

pub const LinkType = enum(u32) {
    null = 0, // DLT_NULL: 4-byte host-order AF header (2 = IPv4, 24/28/30 = IPv6)
    ethernet = 1,
    raw = 101,
    linux_sll = 113,
    _,
};

pub const GlobalHeader = struct {
    endian: std.builtin.Endian,
    nanosecond: bool,
    version_major: u16,
    version_minor: u16,
    snaplen: u32,
    link_type: LinkType,
};

pub const Record = struct {
    ts_sec: u32,
    /// Microseconds or nanoseconds depending on `GlobalHeader.nanosecond`.
    ts_frac: u32,
    orig_len: u32,
    /// Captured bytes (may be shorter than orig_len when snaplen truncated the packet).
    data: []const u8,
};

pub const Reader = struct {
    header: GlobalHeader,
    bytes: []const u8,
    pos: usize,

    /// Parses the 24-byte global header. `error.UnsupportedFormat` for pcapng (0a0d0d0a), unknown magic or a
    /// major version other than 2; `error.Truncated` if the file is shorter than the global header.
    pub fn init(bytes: []const u8) ParseError!Reader {
        if (bytes.len < 4) return error.Truncated;
        const magic = std.mem.readInt(u32, bytes[0..4], .little);
        const endian: std.builtin.Endian, const nanosecond: bool = switch (magic) {
            magic_usec => .{ .little, false },
            magic_nsec => .{ .little, true },
            @byteSwap(magic_usec) => .{ .big, false },
            @byteSwap(magic_nsec) => .{ .big, true },
            pcapng_magic => return error.UnsupportedFormat,
            else => return error.UnsupportedFormat,
        };
        if (bytes.len < global_header_len) return error.Truncated;
        const version_major = std.mem.readInt(u16, bytes[4..6], endian);
        if (version_major != 2) return error.UnsupportedFormat;
        // bytes[8..16]: thiszone and sigfigs, always 0 in practice and unused here.
        const link_field = std.mem.readInt(u32, bytes[20..24], endian);
        return .{
            .header = .{
                .endian = endian,
                .nanosecond = nanosecond,
                .version_major = version_major,
                .version_minor = std.mem.readInt(u16, bytes[6..8], endian),
                .snaplen = std.mem.readInt(u32, bytes[16..20], endian),
                // Upper bits carry FCS-length metadata (draft-ietf-opsawg-pcap, "LinkType and additional
                // information"); libpcap's LT_LINKTYPE() keeps the low 16 bits.
                .link_type = @enumFromInt(link_field & 0xffff),
            },
            .bytes = bytes,
            .pos = global_header_len,
        };
    }

    /// Next record, or null at end of file. A partial trailing record is `error.Truncated`;
    /// incl_len > orig_len is `error.Malformed`. On error the position does not advance.
    pub fn next(self: *Reader) ParseError!?Record {
        const rest = self.bytes[self.pos..];
        if (rest.len == 0) return null;
        if (rest.len < record_header_len) return error.Truncated;
        const endian = self.header.endian;
        const ts_sec = std.mem.readInt(u32, rest[0..4], endian);
        const ts_frac = std.mem.readInt(u32, rest[4..8], endian);
        const incl_len = std.mem.readInt(u32, rest[8..12], endian);
        const orig_len = std.mem.readInt(u32, rest[12..16], endian);
        if (incl_len > orig_len) return error.Malformed;
        if (rest.len - record_header_len < incl_len) return error.Truncated;
        const data = rest[record_header_len..][0..incl_len];
        self.pos += record_header_len + data.len;
        return .{ .ts_sec = ts_sec, .ts_frac = ts_frac, .orig_len = orig_len, .data = data };
    }
};

