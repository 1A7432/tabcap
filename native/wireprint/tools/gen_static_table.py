#!/usr/bin/env python3
"""RFC 7541 Appendix A (static table) -> src/h2/static_table.zig.

Usage: python3 tools/gen_static_table.py /path/to/rfc7541.txt
The RFC text is not stored in the repo (download from https://www.rfc-editor.org/rfc/rfc7541.txt);
the script parses the 61-row table verbatim and refuses to write if it does not find exactly 61 rows.
"""
import hashlib, pathlib, re, sys
root = pathlib.Path(__file__).resolve().parents[1]
rfc_path = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "rfc7541.txt")
raw = rfc_path.read_bytes()
text = raw.decode("ascii")
start = text.index("Appendix A.  Static Table Definition")
end = text.index("Appendix B.  Huffman Code")
rows = [(i, n, v.strip()) for i, n, v in re.findall(r"^\s+\|\s+(\d+)\s+\|\s+(\S+)\s+\|([^|]*)\|\s*$", text[start:end], re.M)]
assert len(rows) == 61, len(rows)
for i, (idx, name, value) in enumerate(rows, 1):
    assert int(idx) == i, (idx, i)
lines = [
    "//! GENERATED by tools/gen_static_table.py from RFC 7541 Appendix A (sha256 %s)." % hashlib.sha256(raw).hexdigest(),
    "//! Do not edit by hand. Index 1..61 map to `entries[index - 1]`; index 0 is invalid (RFC 7541 Section 2.3.3).",
    "",
    "pub const Entry = struct { name: []const u8, value: []const u8 };",
    "",
    "pub const entries = [61]Entry{",
]
for idx, name, value in rows:
    lines.append('    .{ .name = "%s", .value = "%s" }, // %s' % (name, value, idx))
lines += ["};", ""]
(root / "src" / "h2" / "static_table.zig").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("wrote src/h2/static_table.zig (61 entries)")
