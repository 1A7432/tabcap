#!/usr/bin/env python3
"""spec/hpack-huffman.json (RFC 7541 Appendix B, parsed by script) -> src/h2/huffman_table.zig.

Usage: python3 tools/gen_huffman_table.py   (run from repo root; output is deterministic)
The generated file is data only; the decoder that consumes it lives in src/h2/hpack.zig.
"""
import json, pathlib
root = pathlib.Path(__file__).resolve().parents[1]
doc = json.load(open(root / "spec" / "hpack-huffman.json", encoding="utf-8"))
entries = doc["entries"]
assert len(entries) == 257 and [e["sym"] for e in entries] == list(range(257))
lines = []
lines.append("//! GENERATED by tools/gen_huffman_table.py from spec/hpack-huffman.json (RFC 7541 Appendix B).")
lines.append("//! Do not edit by hand. Source RFC sha256: %s" % doc["source_sha256"])
lines.append("//! Entry i is the code for symbol i (0..255 = byte values, 256 = EOS). `code` is right-aligned in a u32.")
lines.append("")
lines.append("pub const Code = struct { code: u32, len: u8 };")
lines.append("")
lines.append("pub const eos: u16 = 256;")
lines.append("")
lines.append("pub const table = [257]Code{")
for e in entries:
    lines.append("    .{ .code = 0x%s, .len = %d }, // %d" % (e["code_hex"], e["bit_length"], e["sym"]))
lines.append("};")
lines.append("")
(root / "src" / "h2" / "huffman_table.zig").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("wrote src/h2/huffman_table.zig (%d entries)" % len(entries))
